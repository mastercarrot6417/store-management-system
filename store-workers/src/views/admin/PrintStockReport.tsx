import type { CurrentFilters, CurrentStockRow, HistoryFilters, MovementRow } from "../../lib/admin/stock-report";
import { stockLevel } from "../../lib/admin/inventory";
import { formatCount, formatDateTime, formatPrice } from "../../lib/format";
import { Document } from "../Document";

export type PrintReportType = "all" | "current" | "history";

type Props = {
  reportType: PrintReportType;
  generatedAt: string;
  generatedBy: string;
  isBoss: boolean;
  current: { filters: CurrentFilters; rows: CurrentStockRow[] } | null;
  history: { filters: HistoryFilters; rows: MovementRow[] } | null;
  /** Filter dropdown labels, so the summary shows names rather than IDs. */
  productLabel: (id: number) => string;
  colourLabel: (id: number) => string;
};

const LEVEL_LABEL = { out: "Out of Stock", low: "Low Stock", in: "In Stock" } as const;

const show = (value: string) => value || "All";

/** Printable stock report, ported from admin/print_stock_report.php. */
export function PrintStockReport(p: Props) {
  return (
    <Document title="Print Stock Report - My Dream Bike Admin" fonts="admin" stylesheets={["/assets/css/print-report.css"]} scripts={["/assets/js/admin.js"]}>
      <div class="print-shell">
        <div class="print-actions">
          <button class="print-btn js-print" type="button">Print Report</button>
          <a class="print-btn secondary" href="/admin/reports/stock">Back to Stock Report</a>
        </div>

        <div class="print-topbar">
          <div class="print-brand">
            <img src="/company_logo/ori.logo.png" alt="My Dream Bike" />
            <div>
              <h1>My Dream Bike Stock Report</h1>
              <p>Inventory report generated from the admin panel.</p>
            </div>
          </div>
          <div class="print-meta">
            <p><strong>Generated:</strong> {formatDateTime(p.generatedAt)}</p>
            <p><strong>Report Type:</strong> {p.reportType[0]!.toUpperCase() + p.reportType.slice(1)}</p>
            <p><strong>Generated By:</strong> {p.generatedBy}</p>
          </div>
        </div>

        {p.current && (
          <section class="report-section">
            <h2>Current Stock Levels</h2>
            <div class="report-count">{formatCount(p.current.rows.length)} current stock row(s)</div>
            <div class="filter-summary">
              <div><span>Search</span>{show(p.current.filters.search)}</div>
              <div><span>Product</span>{p.current.filters.productId ? p.productLabel(p.current.filters.productId) : "All"}</div>
              <div><span>Colour</span>{p.current.filters.colourId ? p.colourLabel(p.current.filters.colourId) : "All"}</div>
              <div><span>Size</span>{show(p.current.filters.size)}</div>
              <div><span>Category</span>{show(p.current.filters.category)}</div>
              <div><span>Subcategory</span>{show(p.current.filters.subCategory)}</div>
              <div><span>Status</span>{show(p.current.filters.status)}</div>
            </div>
            {p.current.rows.length > 0 ? (
              <table>
                <thead>
                  <tr>
                    <th>Item Code</th><th>Product</th><th>Category</th><th>Subcategory</th><th>Colour</th><th>Size</th><th>Qty</th><th>Price</th>
                    {p.isBoss && <th>Online Price</th>}<th>Status</th>
                  </tr>
                </thead>
                <tbody>
                  {p.current.rows.map((row) => {
                    const level = stockLevel(row.quantity);
                    return (
                      <tr>
                        <td>{row.itemCode}</td>
                        <td>{row.name}<br /><small>{row.brand}</small></td>
                        <td>{row.category}</td>
                        <td>{row.subCategory}</td>
                        <td>{row.colourName}</td>
                        <td>{row.size}</td>
                        <td>{row.quantity}</td>
                        <td>RM {formatPrice(row.price)}</td>
                        {p.isBoss && <td>RM {formatPrice(row.onlinePrice)}</td>}
                        <td><span class={`badge ${level}`}>{LEVEL_LABEL[level]}</span></td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            ) : (
              <div class="empty">No current stock rows match the selected filters.</div>
            )}
          </section>
        )}

        {p.history && (
          <section class="report-section">
            <h2>Stock Movement History</h2>
            <div class="report-count">{formatCount(p.history.rows.length)} movement record(s)</div>
            <div class="filter-summary">
              <div><span>Search</span>{show(p.history.filters.search)}</div>
              <div><span>Product</span>{p.history.filters.productId ? p.productLabel(p.history.filters.productId) : "All"}</div>
              <div><span>Colour</span>{p.history.filters.colourId ? p.colourLabel(p.history.filters.colourId) : "All"}</div>
              <div><span>Size</span>{show(p.history.filters.size)}</div>
              <div><span>Type</span>{show(p.history.filters.type)}</div>
              <div><span>Date From</span>{show(p.history.filters.dateFrom)}</div>
              <div><span>Date To</span>{show(p.history.filters.dateTo)}</div>
            </div>
            {p.history.rows.length > 0 ? (
              <table>
                <thead>
                  <tr><th>Date</th><th>Item Code</th><th>Product</th><th>Colour</th><th>Size</th><th>Type</th><th>Before</th><th>Change</th><th>After</th><th>Reason / Note</th><th>Edited By</th></tr>
                </thead>
                <tbody>
                  {p.history.rows.map((row) => (
                    <tr>
                      <td>{formatDateTime(row.createdAt)}</td>
                      <td>{row.itemCode}</td>
                      <td>{row.productName}</td>
                      <td>{row.colourName}</td>
                      <td>{row.size}</td>
                      <td><span class={`badge ${row.type === "IN" ? "stock-in" : "stock-out"}`}>{row.type === "IN" ? "Stock In" : "Stock Out"}</span></td>
                      <td>{row.before}</td>
                      <td>{(row.type === "IN" ? "+" : "-") + row.quantity}</td>
                      <td>{row.after}</td>
                      <td>{row.reason}{row.note && <><br /><small>Note: {row.note}</small></>}</td>
                      <td>{row.editedBy}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            ) : (
              <div class="empty">No stock movement records match the selected filters.</div>
            )}
          </section>
        )}
      </div>
    </Document>
  );
}
