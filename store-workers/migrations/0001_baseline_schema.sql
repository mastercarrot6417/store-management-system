-- ==========================================================
-- 0001 Baseline schema
--
-- Replaces the runtime schema code in the PHP project:
--   admin/includes/schema_helpers.php  (ensureBossPricingSchema,
--                                       ensureStockHistoryAuditSchema,
--                                       ensureInventoryMovementSchema)
--   customer_helpers.php                (ensureCustomersTable)
--   CREATE TABLE blocks in add_product.php / manage_product_colors.php
-- and matches database/latest_database_schema.sql.
--
-- Safe to run on:
--   * an empty database (creates everything), and
--   * the existing production database (every statement is IF NOT EXISTS
--     or only fills NULLs, so existing data is untouched).
--
-- Structure only. Legacy stock clean-up and the colour + size unique rule
-- are in 0002 so data changes are kept separate.
-- ==========================================================

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

-- ---------- admin ----------
CREATE TABLE IF NOT EXISTS admin (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password TEXT NOT NULL,
  role TEXT DEFAULT 'admin',
  display_name TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

ALTER TABLE admin
  ADD COLUMN IF NOT EXISTS role TEXT DEFAULT 'admin',
  ADD COLUMN IF NOT EXISTS display_name TEXT,
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW();

UPDATE admin SET role = 'admin' WHERE role IS NULL OR role = '';

-- ---------- customers ----------
CREATE TABLE IF NOT EXISTS customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  phone TEXT,
  password TEXT NOT NULL,
  google_id TEXT UNIQUE,
  auth_provider TEXT DEFAULT 'email',
  profile_picture TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

ALTER TABLE customers
  ADD COLUMN IF NOT EXISTS google_id TEXT UNIQUE,
  ADD COLUMN IF NOT EXISTS auth_provider TEXT DEFAULT 'email',
  ADD COLUMN IF NOT EXISTS profile_picture TEXT,
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW();

-- ---------- products ----------
CREATE TABLE IF NOT EXISTS products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  brand TEXT NOT NULL,
  category TEXT NOT NULL,
  sub_category TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'ACTIVE',
  price NUMERIC(10,2) NOT NULL DEFAULT 0.00,
  cost_price NUMERIC(10,2) DEFAULT 0,
  online_sell_price NUMERIC(10,2) DEFAULT 0,
  description TEXT,
  image TEXT DEFAULT '',
  arrival_date DATE,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

ALTER TABLE products
  ADD COLUMN IF NOT EXISTS cost_price NUMERIC(10,2) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS online_sell_price NUMERIC(10,2) DEFAULT 0,
  ADD COLUMN IF NOT EXISTS image TEXT DEFAULT '',
  ADD COLUMN IF NOT EXISTS arrival_date DATE,
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW();

UPDATE products SET cost_price = 0 WHERE cost_price IS NULL;
UPDATE products SET online_sell_price = 0 WHERE online_sell_price IS NULL;

-- Production has this rule (checked 2026-10-14), so new databases get it too.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'products_status_check') THEN
    ALTER TABLE products
      ADD CONSTRAINT products_status_check CHECK (status IN ('ACTIVE', 'HIDDEN', 'OUT_OF_STOCK'));
  END IF;
END $$;

-- ---------- product colours and images ----------
CREATE TABLE IF NOT EXISTS product_colors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_name TEXT NOT NULL DEFAULT '',
  color_code TEXT NOT NULL DEFAULT '#000000',
  is_default BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS product_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_id BIGINT REFERENCES product_colors(id) ON DELETE SET NULL,
  image_path TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  is_main BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

-- ---------- stock by product + colour + size ----------
-- color_id has no foreign key, matching production (the column was added later
-- with a plain ALTER TABLE). The app checks a colour belongs to the product itself.
CREATE TABLE IF NOT EXISTS product_sizes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_id BIGINT,
  size TEXT NOT NULL,
  quantity INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

ALTER TABLE product_sizes
  ADD COLUMN IF NOT EXISTS color_id BIGINT,
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW();

-- ---------- stock movement history (audit) ----------
-- color_id has no foreign key, matching production. That also keeps the
-- colour ID in old history rows if a colour is later deleted.
CREATE TABLE IF NOT EXISTS stock_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  color_id BIGINT,
  size TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('IN', 'OUT')),
  quantity INTEGER NOT NULL,
  reason TEXT DEFAULT '',
  quantity_before INTEGER DEFAULT 0,
  quantity_after INTEGER DEFAULT 0,
  note TEXT,
  edited_by_admin_id BIGINT,
  edited_by_admin_name TEXT,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW()
);

ALTER TABLE stock_history
  ADD COLUMN IF NOT EXISTS color_id BIGINT,
  ADD COLUMN IF NOT EXISTS quantity_before INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS quantity_after INTEGER DEFAULT 0,
  ADD COLUMN IF NOT EXISTS note TEXT,
  ADD COLUMN IF NOT EXISTS edited_by_admin_id BIGINT,
  ADD COLUMN IF NOT EXISTS edited_by_admin_name TEXT,
  ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW(),
  ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NOW();

UPDATE stock_history SET quantity_before = 0 WHERE quantity_before IS NULL;
UPDATE stock_history SET quantity_after = quantity WHERE quantity_after IS NULL;

-- ---------- updated_at triggers ----------
DROP TRIGGER IF EXISTS trg_admin_updated_at ON admin;
CREATE TRIGGER trg_admin_updated_at
  BEFORE UPDATE ON admin
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_products_updated_at ON products;
CREATE TRIGGER trg_products_updated_at
  BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_product_sizes_updated_at ON product_sizes;
CREATE TRIGGER trg_product_sizes_updated_at
  BEFORE UPDATE ON product_sizes
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_stock_history_updated_at ON stock_history;
CREATE TRIGGER trg_stock_history_updated_at
  BEFORE UPDATE ON stock_history
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------- indexes ----------
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_sub_category ON products(sub_category);
CREATE INDEX IF NOT EXISTS idx_products_status ON products(status);
CREATE INDEX IF NOT EXISTS idx_product_colors_product_id ON product_colors(product_id);
CREATE INDEX IF NOT EXISTS idx_product_images_product_id ON product_images(product_id);
CREATE INDEX IF NOT EXISTS idx_product_images_color_id ON product_images(color_id);
CREATE INDEX IF NOT EXISTS idx_product_sizes_product_id ON product_sizes(product_id);
CREATE INDEX IF NOT EXISTS idx_product_sizes_product_color_size ON product_sizes(product_id, color_id, size);
CREATE INDEX IF NOT EXISTS idx_stock_history_product_id ON stock_history(product_id);
CREATE INDEX IF NOT EXISTS idx_stock_history_product_color_size ON stock_history(product_id, color_id, size);
CREATE INDEX IF NOT EXISTS idx_stock_history_created_at ON stock_history(created_at);
